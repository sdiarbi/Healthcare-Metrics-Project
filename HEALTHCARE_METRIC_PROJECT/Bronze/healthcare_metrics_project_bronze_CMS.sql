-- 4. BRONZE_SNF_VBP_PERFORMANCE
--------------------------------------------------------------------------------
CREATE OR REPLACE TABLE BRONZE.BRONZE_SNF_VBP_PERFORMANCE AS
SELECT
    TRY_CAST(BASELINE_PERIOD_FY_2019_NATIONAL_AVERAGE_READMISSION_RATE AS FLOAT)    AS BASELINE_2019_READMISSION_RATE,
    TRY_CAST(PERFORMANCE_PERIOD_FY_2022_NATIONAL_AVERAGE_READMISSION_RATE AS FLOAT) AS PERFORMANCE_2022_READMISSION_RATE,
    TRY_CAST(FY_2024_ACHIEVEMENT_THRESHOLD AS FLOAT) AS FY2024_ACHIEVEMENT_THRESHOLD,
    TRY_CAST(FY_2024_BENCHMARK AS FLOAT)             AS FY2024_BENCHMARK,
    RANGE_OF_PERFORMANCE_SCORES,
    TRY_CAST(TOTAL_NUMBER_OF_SNFS_RECEIVING_VALUE_BASED_INCENTIVE_PAYMENTS AS INT) AS TOTAL_SNFS_RECEIVING_INCENTIVE,
    RANGE_OF_INCENTIVE_PAYMENT_MULTIPLIERS,
    RANGE_OF_VALUE_BASED_INCENTIVE_PAYMENTS_DOLLARS  AS INCENTIVE_PAYMENTS_RANGE_DOLLARS,
    TRY_CAST(REPLACE(REPLACE(TOTAL_AMOUNT_OF_VALUE_BASED_INCENTIVE_PAYMENTS_DOLLARS, '$', ''), ',', '') AS FLOAT) AS TOTAL_INCENTIVE_PAYMENTS_DOLLARS,
    CURRENT_TIMESTAMP()                              AS _INGESTED_AT,
    'FY_2024_SNF_VBP_Aggregate_Performance.csv'     AS _SOURCE_FILE
FROM RAW.RAW_SNF_VBP_PERFORMANCE;


